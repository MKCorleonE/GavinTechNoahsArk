"""
题目：牛牛涂格子

牛牛有一排 N 个格子，每个格子最终需要被涂成红色（R）或蓝色（B）。

每次操作可以选择一段连续的格子，并将这一整段格子涂成同一种颜色。
后续操作允许覆盖之前已经涂过的颜色。

请计算：将所有格子涂成目标颜色所需的最少操作次数。

例如：
N = 8
目标颜色：BBRBRBBR

一种较优方案：
1. 将第 1～7 个格子全部涂成蓝色
2. 将第 3 个格子涂成红色
3. 将第 5 个格子涂成红色
4. 将第 8 个格子涂成红色

因此最少操作次数为 4。

输入：
第一行：整数 N，表示格子数量。
第二行：长度为 N 的字符串，只包含字符 R 和 B。
其中 R 表示红色，B 表示蓝色。

输出：
输出一个整数，表示最少操作次数。

数据范围：
1 <= N <= 500000

示例输入：
8
BBRBRBBR

示例输出：
4
"""

# 最佳答案
import sys

data = sys.stdin.read().split() # 读取所有输入数据（笔试中常用）
n = int(data[0])
s = data[1]

blue_runs = 0   # 蓝色连续段数量
red_runs = 0    # 红色连续段数量
prev = ''       # 保存前一个格子的颜色

for ch in s:
    # 当前颜色与前一个颜色不同时，说明进入了新的连续段
    if ch != prev:
        if ch == 'B':
            blue_runs += 1
        else:
            red_runs += 1

        prev = ch

print(min(blue_runs, red_runs) + 1)