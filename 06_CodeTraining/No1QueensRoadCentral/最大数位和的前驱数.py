"""
给定一个由 N 位数字组成的字符串 S，它表示一个正整数。
请找出所有严格小于 S 的正整数中，各位数字之和最大的那个数，并以字符串形式返回。

若有多个数字的各位和同样最大，返回其中任意一个即可。
返回值只能包含数字，且不能有前导零。
S 本身没有前导零。
N 的范围是 2 到 100000，因此需要高效算法。

例如：
- S = "899"：可返回 "898"，因为数字和为 8+9+8=25
- S = "10"：只能返回 "9"
- S = "98"：返回 "89"，数字和为 17，比 "97" 的 16 更大
"""

# 最佳答案
def Solution(S: str) -> str:
    n = len(S)
    # 将字符串转换为列表以便修改
    digits = list(S)
    # 从右向左找到第一个可以减少的数字
    for i in range(n - 1, 0, -1):
        if digits[i] > '0':
            # 减少当前数字
            digits[i] = str(int(digits[i]) - 1)
            # 将后面的所有数字变为 '9'
            for j in range(i + 1, n):
                digits[j] = '9'
            break
    else:
        # 如果没有找到可以减少的数字，说明 S 是最小的两位数，返回 '9'
        return '9'
    
    # 去掉前导零
    result = ''.join(digits).lstrip('0')
    
    return result if result else '0'

# 复杂度分析：
# 时间复杂度：O(N)，其中 N 是字符串 S 的长度。我们最多需要遍历一次字符串 S。
# 空间复杂度：O(N)，用于存储修改后的数字列表。

# 笔记
# for else结构：如果 for 循环正常结束（没有被 break 中断），则执行 else 块中的代码。