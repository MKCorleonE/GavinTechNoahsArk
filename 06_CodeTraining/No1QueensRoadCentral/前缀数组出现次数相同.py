"""
给定两个整数：
- Jacob 喜欢的数字 X
- Jayden 喜欢的数字 Y
- 一个非空整数数组 A，长度为 N
需要找到最大的下标 P（满足 0 ≤ P < N），使得前缀数组 A[0..P] 中，数字 X 出现的次数与数字 Y 出现的次数相同。
- 如果存在这样的 P，返回最大的那个 P。
- 如果不存在任何满足条件的前缀，返回 -1。
例如：
- X = 7，Y = 42
- A = [6, 42, 11, 7, 1, 42]
满足条件的前缀包括：
- P = 0：[6]，7 和 42 都出现 0 次
- P = 3：[6, 42, 11, 7]，7 和 42 各出现 1 次
- P = 4：[6, 42, 11, 7, 1]，7 和 42 各出现 1 次
因此应返回 4。P = 5 时，42 出现两次、7 出现一次，不满足条件。
另一个例子：
- X = 6，Y = 13
- A = [13, 13, 1, 6]
任何非空前缀中，6 和 13 的出现次数都不相等，所以返回 -1。
第三个例子：
- X = 100，Y = 63
- A = [100, 1, 1, 63, 2, 13]
完整数组中 100 和 63 都出现一次，因此最大合法下标为 5，返回 5。
限制条件：
- N 在 1 到 100,000 之间；
- X、Y 在 1 到 1,000,000,000 之间；
- 数组每个元素也在 1 到 1,000,000,000 之间。
现有代码在部分输入下会出错。你的任务是找出并修复问题，并且最多只能修改两行代码。题目主要考察正确性，不重点考察性能。
"""

# 原始代码，只能修改两行
def solution(X, Y, A):
    N = len(A)
    result = -1
    nX = 0
    nY = 0

    for i in range(N):
        if A[i] == X:
            nX += 1
        elif A[i] == Y:
            nY += 1

        if nX == nY:
            result = 1

    return result

