def solution(X, Y, A):
    N = len(A)
    result = -1
    nX = 0
    nY = 0

    for i in range(N):
        if A[i] == X:
            nX += 1
        if A[i] == Y:       # 把 elif 改为 if，因为elif 会在 A[i] == X 时跳过对 A[i] == Y 的检查
            nY += 1

        if nX == nY:
            result = i      # 把 1 改为 i

    return result

# if 和 elif 的区别在于，if 会继续检查下一个条件，而 elif 在前一个条件为真时会跳过后续条件。
