"""
给你一个仅由数字（0 - 9）组成的字符串 num 。

请你找出能够使用 num 中数字形成的 最大回文 整数，并以字符串形式返回。该整数不含 前导零 。

注意：

你 无需 使用 num 中的所有数字，但你必须使用 至少 一个数字。
数字可以重新排序。

示例 1：
输入：num = "444947137"
输出："7449447"
解释：
从 "444947137" 中选用数字 "4449477"，可以形成回文整数 "7449447" 。
可以证明 "7449447" 是能够形成的最大回文整数。

示例 2：
输入：num = "00009"
输出："9"
解释：
可以证明 "9" 能够形成的最大回文整数。
注意返回的整数不应含前导零。
为什么不是“0000”呢？因为返回的整数不应含前导零。
"""

# 最佳答案，贪心算法
from collections import Counter

class Solution:
    def largestPalindromic(self, num: str) -> str:
        cnt = Counter(num)
        if cnt['0'] == len(num):  # 特判最特殊的情况：num 全是 0
            return "0"

        s = ""   # 回文串的左半部分
        # 从大到小的数字顺序,力扣一般默认提供string.digits：‘0123456789’
        for d in digits[:0:-1]:
            s += d * (cnt[d] // 2)
        if s:  # 如果填了数字，则可以填 0
            s += '0' * (cnt['0'] // 2)

        t = s[::-1]   # 回文串的右半部分，操作方式是将左半部分翻转
        for d in digits[::-1]:
            if cnt[d] % 2:  # 还可以填一个变成奇回文串
                s += d
                break   # 只需要填一个最大的奇数位数字即可
        return s + t  # 添加镜像部分

# 复杂度分析
# 时间复杂度：O(n)，其中 n 是字符串 num 的长度。
# 空间复杂度：O(1)，因为字符集的大小是固定的（最多 10 个数字）。

# 什么是回文数
# 回文数是指正着读和反着读都一样的整数。例如，121、12321、1234321 都是回文数，而 123、1234、12345 都不是回文数。